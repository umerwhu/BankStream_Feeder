-- First-time setup: run with SQL*Plus or SQLcl connected as a DBA to CDB$ROOT.
-- C##BANKCRM is a common user; create it at the root, then grant only in the target PDB.
-- Enter the PDB name and connect service when prompted. USERS is the default tablespace;
-- change it below if your PDB uses a different application tablespace.

CREATE USER C##BANKCRM IDENTIFIED BY "&&BANKCRM_PASSWORD" CONTAINER=ALL;
ALTER SESSION SET CONTAINER = &&BANKCRM_PDB_NAME;
GRANT CREATE SESSION, CREATE TABLE, CREATE INDEX TO C##BANKCRM CONTAINER=CURRENT;
ALTER USER C##BANKCRM DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS CONTAINER=CURRENT;
CONNECT C##BANKCRM/"&&BANKCRM_PASSWORD"@&&BANKCRM_PDB_SERVICE

CREATE TABLE C##BANKCRM.CUSTOMER_PROFILE (

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL PRIMARY KEY,

 CUSTOMER_ID NUMBER(19) NOT NULL UNIQUE,

 EMAIL VARCHAR2(254),

 PHONE_NUMBER VARCHAR2(30),

 COUNTRY CHAR(2),

 SEGMENT VARCHAR2(30),

 PREFERRED_CHANNEL VARCHAR2(20),

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 CHECK (COUNTRY IN ('US','GB','AU')),

 CHECK (PREFERRED_CHANNEL IN ('BRANCH','PHONE','EMAIL','MOBILE','WEB'))

);

CREATE TABLE C##BANKCRM.CUSTOMER_ADDRESS (

 ADDRESS_ID VARCHAR2(30) NOT NULL PRIMARY KEY,

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL,

 ADDRESS_TYPE VARCHAR2(20) NOT NULL,

 STREET_ADDRESS VARCHAR2(200) NOT NULL,

 ADDRESS_LINE_2 VARCHAR2(200),

 CITY VARCHAR2(80) NOT NULL,

 REGION VARCHAR2(80),

 POSTAL_CODE VARCHAR2(20),

 COUNTRY CHAR(2) NOT NULL,

 IS_PRIMARY CHAR(1) DEFAULT 'N' NOT NULL,

 VALID_FROM DATE,

 VALID_TO DATE,

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_PROFILE_ID)

   REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_PROFILE_ID),

 CHECK (ADDRESS_TYPE IN ('RESIDENTIAL','MAILING','BUSINESS')),

 CHECK (IS_PRIMARY IN ('Y','N')),

 CHECK (COUNTRY IN ('US','GB','AU'))

);

CREATE INDEX C##BANKCRM.IX_ADDRESS_PROFILE

 ON C##BANKCRM.CUSTOMER_ADDRESS(CUSTOMER_PROFILE_ID);

CREATE TABLE C##BANKCRM.CUSTOMER_KYC (

 KYC_RECORD_ID VARCHAR2(30) NOT NULL PRIMARY KEY,

 CUSTOMER_ID NUMBER(19) NOT NULL UNIQUE,

 KYC_STATUS VARCHAR2(20) NOT NULL,

 RISK_RATING VARCHAR2(20),

 LAST_REVIEW_DATE DATE,

 NEXT_REVIEW_DATE DATE,

 CUSTOMER_COUNTRY CHAR(2),

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_ID) REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_ID),

 CHECK (KYC_STATUS IN ('PENDING','VERIFIED','REJECTED','REVIEW_REQUIRED','EXPIRED')),

 CHECK (RISK_RATING IN ('LOW','MEDIUM','HIGH')),

 CHECK (CUSTOMER_COUNTRY IN ('US','GB','AU'))

);

CREATE TABLE C##BANKCRM.CUSTOMER_SERVICE_CASE (

 SERVICE_CASE_ID VARCHAR2(30) NOT NULL PRIMARY KEY,

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL,

 CASE_TYPE VARCHAR2(30) NOT NULL,

 CASE_SUBJECT VARCHAR2(200) NOT NULL,

 CASE_DESCRIPTION VARCHAR2(2000),

 PRIORITY VARCHAR2(12) DEFAULT 'MEDIUM' NOT NULL,

 CASE_STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,

 OPENED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 RESOLVED_TIMESTAMP TIMESTAMP,

 ASSIGNED_TEAM VARCHAR2(80),

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_PROFILE_ID) REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_PROFILE_ID),

 CHECK (PRIORITY IN ('LOW','MEDIUM','HIGH','URGENT')),

 CHECK (CASE_STATUS IN ('OPEN','IN_PROGRESS','WAITING_CUSTOMER','RESOLVED','CLOSED'))

);

CREATE TABLE C##BANKCRM.CUSTOMER_INTERACTIONS (

 CUSTOMER_INTERACTION_ID VARCHAR2(40) NOT NULL PRIMARY KEY,

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL,

 INTERACTION_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 INTERACTION_TYPE VARCHAR2(30) NOT NULL,

 CHANNEL VARCHAR2(20),

 SUMMARY VARCHAR2(1000),

 SERVICE_CASE_ID VARCHAR2(30),

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_PROFILE_ID) REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_PROFILE_ID),

 FOREIGN KEY (SERVICE_CASE_ID) REFERENCES C##BANKCRM.CUSTOMER_SERVICE_CASE(SERVICE_CASE_ID),

 CHECK (INTERACTION_TYPE IN ('CALL','EMAIL','CHAT','BRANCH_VISIT','MOBILE_APP','WEB')),

 CHECK (CHANNEL IN ('BRANCH','PHONE','EMAIL','MOBILE','WEB'))

);

CREATE TABLE CUSTOMER_OFFERS (
    PRODUCT_OFFER_ID VARCHAR2(30) NOT NULL PRIMARY KEY,
    CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL,
    PRODUCT_CODE VARCHAR2(30) NOT NULL,
    OFFER_TYPE VARCHAR2(30) NOT NULL,
    OFFER_STATUS VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    OFFER_DATE DATE NOT NULL,
    EXPIRY_DATE DATE,
    LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_OFFERS_PROFILE
        FOREIGN KEY (CUSTOMER_PROFILE_ID)
        REFERENCES CUSTOMER_PROFILE (CUSTOMER_PROFILE_ID),
    CONSTRAINT CK_OFFERS_STATUS
        CHECK (OFFER_STATUS IN ('AVAILABLE', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'WITHDRAWN'))
);

CREATE TABLE C##BANKCRM.CUSTOMER_PREFERENCE (

 CUSTOMER_PREFERENCE_ID VARCHAR2(30) NOT NULL PRIMARY KEY,

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL UNIQUE,

 PREFERRED_LANGUAGE VARCHAR2(20) DEFAULT 'en',

 STATEMENT_DELIVERY VARCHAR2(20),

 NOTIFICATION_CHANNEL VARCHAR2(20),

 DO_NOT_CONTACT CHAR(1) DEFAULT 'N' NOT NULL,

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_PROFILE_ID) REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_PROFILE_ID),

 CHECK (DO_NOT_CONTACT IN ('Y','N')),

 CHECK (STATEMENT_DELIVERY IN ('PAPER','ELECTRONIC')),

 CHECK (NOTIFICATION_CHANNEL IN ('EMAIL','SMS','PUSH','PHONE','NONE'))

);

CREATE TABLE C##BANKCRM.CUSTOMER_CONSENT (

 CONSENT_ID VARCHAR2(40) NOT NULL PRIMARY KEY,

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL,

 CONSENT_TYPE VARCHAR2(30) NOT NULL,

 CONSENT_STATUS VARCHAR2(20) NOT NULL,

 CAPTURED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 SOURCE_CHANNEL VARCHAR2(20),

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_PROFILE_ID) REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_PROFILE_ID),

 CHECK (CONSENT_TYPE IN ('MARKETING','DATA_SHARING','PERSONALIZATION')),

 CHECK (CONSENT_STATUS IN ('GRANTED','REVOKED','PENDING')),

 CHECK (SOURCE_CHANNEL IN ('BRANCH','PHONE','EMAIL','MOBILE','WEB'))

);

CREATE TABLE C##BANKCRM.CUSTOMER_CAMPAIGN_RESPONSE (

 CAMPAIGN_RESPONSE_ID VARCHAR2(40) NOT NULL PRIMARY KEY,

 CUSTOMER_PROFILE_ID VARCHAR2(30) NOT NULL,

 CAMPAIGN_CODE VARCHAR2(30) NOT NULL,

 RESPONSE_STATUS VARCHAR2(20) NOT NULL,

 SENT_TIMESTAMP TIMESTAMP,

 RESPONSE_TIMESTAMP TIMESTAMP,

 CHANNEL VARCHAR2(20),

 LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

 FOREIGN KEY (CUSTOMER_PROFILE_ID) REFERENCES C##BANKCRM.CUSTOMER_PROFILE(CUSTOMER_PROFILE_ID),

 CHECK (RESPONSE_STATUS IN ('SENT','DELIVERED','OPENED','CLICKED','ACCEPTED','DECLINED','BOUNCED')),

 CHECK (CHANNEL IN ('BRANCH','PHONE','EMAIL','MOBILE','WEB'))

);





CREATE INDEX C##BANKCRM.IX_KYC_STATUS ON C##BANKCRM.CUSTOMER_KYC(KYC_STATUS,RISK_RATING);

