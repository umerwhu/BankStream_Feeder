GRANT SELECT, INSERT, UPDATE
ON TABLE BANKCORE.CUSTOMER
TO USER username;

CREATE SCHEMA BANKCORE;

SET CURRENT SCHEMA = BANKCORE;

CREATE TABLE BANKCORE.CUSTOMER (

 CUSTOMER_ID BIGINT NOT NULL PRIMARY KEY,

 CUSTOMER_NAME VARCHAR(120) NOT NULL,

 CUSTOMER_TYPE VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL',

 DATE_OF_BIRTH DATE,

 GENDER VARCHAR(20),

 NATIONAL_IDENTIFICATION_NUMBER VARCHAR(40),

 BRANCH_CODE VARCHAR(20),

 CUSTOMER_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 OPENING_DATE DATE NOT NULL DEFAULT CURRENT DATE,

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 CHECK (CUSTOMER_TYPE IN ('INDIVIDUAL','BUSINESS')),

 CHECK (CUSTOMER_STATUS IN ('ACTIVE','INACTIVE','SUSPENDED','CLOSED'))

);

CREATE TABLE BANKCORE.BANK_BRANCH (

 BRANCH_CODE VARCHAR(20) NOT NULL PRIMARY KEY,

 BRANCH_NAME VARCHAR(120) NOT NULL,

 CITY VARCHAR(80) NOT NULL,

 COUNTRY CHAR(2) NOT NULL,

 BRANCH_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 CHECK (BRANCH_STATUS IN ('ACTIVE','INACTIVE','CLOSED'))

);

CREATE TABLE BANKCORE.BANK_ACCOUNT (

 ACCOUNT_ID VARCHAR(30) NOT NULL PRIMARY KEY,

 ACCOUNT_NUMBER VARCHAR(34) NOT NULL UNIQUE,

 ACCOUNT_TYPE VARCHAR(24) NOT NULL,

 CURRENCY CHAR(3) NOT NULL,

 BALANCE DECIMAL(19,4) NOT NULL DEFAULT 0,

 AVAILABLE_BALANCE DECIMAL(19,4) NOT NULL DEFAULT 0,

 ACCOUNT_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 OPENING_DATE DATE NOT NULL DEFAULT CURRENT DATE,

 BRANCH_CODE VARCHAR(20),

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (BRANCH_CODE) REFERENCES BANKCORE.BANK_BRANCH(BRANCH_CODE),

 CHECK (ACCOUNT_TYPE IN ('CHECKING','SAVINGS','BUSINESS','OTHER')),

 CHECK (ACCOUNT_STATUS IN ('ACTIVE','DORMANT','FROZEN','CLOSED'))

);

CREATE TABLE BANKCORE.ACCOUNT_CUSTOMER_RELATIONSHIP (

 ACCOUNT_ID VARCHAR(30) NOT NULL,

 CUSTOMER_ID BIGINT NOT NULL,

 OWNERSHIP_ROLE VARCHAR(20) NOT NULL DEFAULT 'PRIMARY',

 EFFECTIVE_FROM DATE NOT NULL DEFAULT CURRENT DATE,

 EFFECTIVE_TO DATE,

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 PRIMARY KEY (ACCOUNT_ID,CUSTOMER_ID),

 FOREIGN KEY (ACCOUNT_ID) REFERENCES BANKCORE.BANK_ACCOUNT(ACCOUNT_ID),

 FOREIGN KEY (CUSTOMER_ID) REFERENCES BANKCORE.CUSTOMER(CUSTOMER_ID),

 CHECK (OWNERSHIP_ROLE IN ('PRIMARY','JOINT','AUTHORIZED','BENEFICIAL_OWNER'))

);

CREATE TABLE BANKCORE.ACCOUNT_TRANSACTION (

 TRANSACTION_ID VARCHAR(40) NOT NULL PRIMARY KEY,

 ACCOUNT_ID VARCHAR(30) NOT NULL,

 CARD_ID VARCHAR(30),

 TRANSACTION_TYPE VARCHAR(30) NOT NULL,

 TRANSACTION_STAGE VARCHAR(20) NOT NULL DEFAULT 'POSTED',

 TRANSACTION_STATUS VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',

 TRANSACTION_AMOUNT DECIMAL(19,4) NOT NULL,

 CURRENCY CHAR(3) NOT NULL,

 TRANSACTION_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 CHANNEL VARCHAR(20),

 COUNTERPARTY_REFERENCE VARCHAR(80),

 RELATED_TRANSACTION_ID VARCHAR(40),

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (ACCOUNT_ID) REFERENCES BANKCORE.BANK_ACCOUNT(ACCOUNT_ID),

 CHECK (TRANSACTION_TYPE IN ('DEPOSIT','WITHDRAWAL','TRANSFER','CARD_PURCHASE','ATM_WITHDRAWAL','BILL_PAYMENT','LOAN_REPAYMENT','FEE','INTEREST','REFUND','REVERSAL')),

 CHECK (TRANSACTION_STAGE IN ('AUTHORIZATION','POSTED','REVERSAL')),

 CHECK (TRANSACTION_STATUS IN ('PENDING','PROCESSING','COMPLETED','REJECTED','CANCELLED','REVERSED'))

);

CREATE TABLE BANKCORE.CARD (

 CARD_ID VARCHAR(30) NOT NULL PRIMARY KEY,

 CUSTOMER_ID BIGINT NOT NULL,

 ACCOUNT_ID VARCHAR(30),

 CARD_TYPE VARCHAR(20) NOT NULL,

 CARD_NETWORK VARCHAR(20),

 MASKED_CARD_NUMBER VARCHAR(25) NOT NULL UNIQUE,

 CARD_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 ISSUE_DATE DATE,

 EXPIRY_DATE DATE,

 CREDIT_LIMIT DECIMAL(19,4),

 CURRENCY CHAR(3),

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (CUSTOMER_ID) REFERENCES BANKCORE.CUSTOMER(CUSTOMER_ID),

 FOREIGN KEY (ACCOUNT_ID) REFERENCES BANKCORE.BANK_ACCOUNT(ACCOUNT_ID),

 CHECK (CARD_TYPE IN ('DEBIT','CREDIT','PREPAID')),

 CHECK (CARD_STATUS IN ('ACTIVE','BLOCKED','EXPIRED','CANCELLED'))

);

CREATE TABLE BANKCORE.LOAN_ACCOUNT (

 LOAN_ACCOUNT_ID VARCHAR(30) NOT NULL PRIMARY KEY,

 CUSTOMER_ID BIGINT NOT NULL,

 LOAN_TYPE VARCHAR(24) NOT NULL,

 LOAN_AMOUNT DECIMAL(19,4) NOT NULL,

 OUTSTANDING_BALANCE DECIMAL(19,4) NOT NULL,

 CURRENCY CHAR(3) NOT NULL,

 INTEREST_RATE DECIMAL(7,4),

 START_DATE DATE,

 MATURITY_DATE DATE,

 NEXT_DUE_DATE DATE,

 LOAN_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 BRANCH_CODE VARCHAR(20),

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (CUSTOMER_ID) REFERENCES BANKCORE.CUSTOMER(CUSTOMER_ID),

 FOREIGN KEY (BRANCH_CODE) REFERENCES BANKCORE.BANK_BRANCH(BRANCH_CODE),

 CHECK (LOAN_TYPE IN ('PERSONAL','MORTGAGE','AUTO','BUSINESS','EDUCATION')),

 CHECK (LOAN_STATUS IN ('ACTIVE','PAID_OFF','DELINQUENT','DEFAULTED','CLOSED'))

);

CREATE TABLE BANKCORE.LOAN_REPAYMENT (

 REPAYMENT_ID VARCHAR(40) NOT NULL PRIMARY KEY,

 LOAN_ACCOUNT_ID VARCHAR(30) NOT NULL,

 DUE_DATE DATE NOT NULL,

 DUE_AMOUNT DECIMAL(19,4) NOT NULL,

 PAID_AMOUNT DECIMAL(19,4) NOT NULL DEFAULT 0,

 PAYMENT_DATE DATE,

 REPAYMENT_STATUS VARCHAR(20) NOT NULL DEFAULT 'DUE',

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (LOAN_ACCOUNT_ID) REFERENCES BANKCORE.LOAN_ACCOUNT(LOAN_ACCOUNT_ID),

 CHECK (REPAYMENT_STATUS IN ('DUE','PARTIAL','PAID','OVERDUE','WAIVED'))

);

CREATE TABLE BANKCORE.PAYMENT_BENEFICIARY (

 BENEFICIARY_ID VARCHAR(30) NOT NULL PRIMARY KEY,

 CUSTOMER_ID BIGINT NOT NULL,

 BENEFICIARY_NAME VARCHAR(120) NOT NULL,

 BANK_NAME VARCHAR(120),

 BENEFICIARY_ACCOUNT_REFERENCE VARCHAR(80) NOT NULL,

 COUNTRY CHAR(2),

 BENEFICIARY_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (CUSTOMER_ID) REFERENCES BANKCORE.CUSTOMER(CUSTOMER_ID),

 CHECK (BENEFICIARY_STATUS IN ('ACTIVE','INACTIVE','BLOCKED'))

);

CREATE TABLE BANKCORE.PAYMENT_INSTRUCTION (

 PAYMENT_ID VARCHAR(40) NOT NULL PRIMARY KEY,

 CUSTOMER_ID BIGINT NOT NULL,

 SOURCE_ACCOUNT_ID VARCHAR(30) NOT NULL,

 BENEFICIARY_ID VARCHAR(30),

 PAYMENT_TYPE VARCHAR(24) NOT NULL,

 PAYMENT_AMOUNT DECIMAL(19,4) NOT NULL,

 CURRENCY CHAR(3) NOT NULL,

 INITIATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 PAYMENT_STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',

 CHANNEL VARCHAR(20),

 REFERENCE_NUMBER VARCHAR(80),

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (CUSTOMER_ID) REFERENCES BANKCORE.CUSTOMER(CUSTOMER_ID),

 FOREIGN KEY (SOURCE_ACCOUNT_ID) REFERENCES BANKCORE.BANK_ACCOUNT(ACCOUNT_ID),

 FOREIGN KEY (BENEFICIARY_ID) REFERENCES BANKCORE.PAYMENT_BENEFICIARY(BENEFICIARY_ID),

 CHECK (PAYMENT_TYPE IN ('DOMESTIC','INTERNATIONAL','INTERNAL_TRANSFER','BILL_PAYMENT')),

 CHECK (PAYMENT_STATUS IN ('PENDING','PROCESSING','COMPLETED','REJECTED','CANCELLED'))

);

CREATE TABLE BANKCORE.TERM_DEPOSIT (

 TERM_DEPOSIT_ID VARCHAR(30) NOT NULL PRIMARY KEY,

 CUSTOMER_ID BIGINT NOT NULL,

 FUNDING_ACCOUNT_ID VARCHAR(30),

 PRINCIPAL_AMOUNT DECIMAL(19,4) NOT NULL,

 CURRENCY CHAR(3) NOT NULL,

 INTEREST_RATE DECIMAL(7,4) NOT NULL,

 OPEN_DATE DATE NOT NULL,

 MATURITY_DATE DATE NOT NULL,

 DEPOSIT_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

 LAST_UPDATED_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,

 FOREIGN KEY (CUSTOMER_ID) REFERENCES BANKCORE.CUSTOMER(CUSTOMER_ID),

 FOREIGN KEY (FUNDING_ACCOUNT_ID) REFERENCES BANKCORE.BANK_ACCOUNT(ACCOUNT_ID),

 CHECK (DEPOSIT_STATUS IN ('ACTIVE','MATURED','RENEWED','CLOSED'))

);

CREATE INDEX BANKCORE.IX_ACR_CUSTOMER ON BANKCORE.ACCOUNT_CUSTOMER_RELATIONSHIP(CUSTOMER_ID);

CREATE INDEX BANKCORE.IX_TXN_ACCOUNT_TS ON BANKCORE.ACCOUNT_TRANSACTION(ACCOUNT_ID,TRANSACTION_TIMESTAMP);

CREATE INDEX BANKCORE.IX_TXN_STATUS_TS ON BANKCORE.ACCOUNT_TRANSACTION(TRANSACTION_STATUS,TRANSACTION_TIMESTAMP);

CREATE INDEX BANKCORE.IX_CARD_CUSTOMER ON BANKCORE.CARD(CUSTOMER_ID);

CREATE INDEX BANKCORE.IX_LOAN_CUSTOMER ON BANKCORE.LOAN_ACCOUNT(CUSTOMER_ID);

CREATE INDEX BANKCORE.IX_REPAYMENT_DUE ON BANKCORE.LOAN_REPAYMENT(LOAN_ACCOUNT_ID,DUE_DATE);

CREATE INDEX BANKCORE.IX_PAYMENT_CUSTOMER_TS ON BANKCORE.PAYMENT_INSTRUCTION(CUSTOMER_ID,INITIATED_TIMESTAMP);

ALTER TABLE BANKCORE.CUSTOMER

 ADD CONSTRAINT FK_CUSTOMER_BRANCH

 FOREIGN KEY (BRANCH_CODE) REFERENCES BANKCORE.BANK_BRANCH(BRANCH_CODE);

ALTER TABLE BANKCORE.ACCOUNT_TRANSACTION

 ADD CONSTRAINT FK_TRANSACTION_CARD

 FOREIGN KEY (CARD_ID) REFERENCES BANKCORE.CARD(CARD_ID);
